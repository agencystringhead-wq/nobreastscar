// Writes public/_redirects (Cloudflare Pages) from scripts/image-map.json.
//   node scripts/make-redirects.mjs
// - Old WordPress sitemaps, feeds and admin URLs go to the new equivalents.
// - Every old /wp-content/uploads/... image URL goes to the same image, now WebP, at /img/<section>/<name>.webp.
//   scripts/publish-legacy-images.mjs copies those files into dist/img/ at build time so the URLs stay stable
//   (the hashed /_astro/ files change whenever an image does).
// "/?p=123" needs no rule: static hosting ignores the query string and serves the home page.
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const map = JSON.parse(await readFile(join(root, 'scripts', 'image-map.json'), 'utf8'));

const lines = [
  '# Cloudflare Pages redirects. Generated by scripts/make-redirects.mjs: edit the script, not this file.',
  '',
  '# Old WordPress sitemaps, feeds and admin',
  '/page-sitemap.xml /sitemap-index.xml 301',
  '/case-study-sitemap.xml /sitemap-index.xml 301',
  '/sitemap_index.xml /sitemap-index.xml 301',
  '/sitemap.xml /sitemap-index.xml 301',
  '/feed/ / 301',
  '/comments/feed/ / 301',
  '/wp-admin/* / 301',
  '/wp-login.php / 301',
  '',
  '# Old WordPress image URLs -> the same image as WebP (kept so Google Images links keep working)',
];
let n = 0;
for (const [oldUrl, file] of Object.entries(map).sort(([a], [b]) => a.localeCompare(b))) {
  const from = new URL(oldUrl).pathname;
  const to = '/img/' + file.replace(/^src\/assets\/images\//, '');
  lines.push(`${from} ${to} 301`);
  n++;
}
await writeFile(join(root, 'public', '_redirects'), lines.join('\n') + '\n');
console.log(`Wrote public/_redirects (${lines.filter((l) => l && !l.startsWith('#')).length} rules, ${n} image redirects)`);
