// Writes the redirects for the move off WordPress, from scripts/image-map.json.
//   node scripts/make-redirects.mjs
//
//  - public/_redirects                       old sitemaps, feeds and admin URLs (a handful of rules)
//  - functions/wp-content/[[path]].js        every old /wp-content/uploads/... image URL -> the same image as WebP at
//                                            /img/<section>/<name>.webp (301). Also matches WordPress resized variants
//                                            such as logo-300x143.jpg.
//  - public/_routes.json                     runs that function only for /wp-content/*, so no other request is affected
//
// Why a function: Cloudflare Pages applied only the first ~100 of 144 individual image rules from _redirects; the rest
// returned 404. The function has no such limit. scripts/publish-legacy-images.mjs copies the WebP files into dist/img/
// at build time so the targets are stable (the hashed /_astro/ files change whenever an image does).
// "/?p=123" needs no rule: static hosting ignores the query string and serves the home page.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const map = JSON.parse(await readFile(join(root, 'scripts', 'image-map.json'), 'utf8'));

// ---- _redirects ----
const rules = [
  '# Cloudflare Pages redirects. Generated by scripts/make-redirects.mjs: edit the script, not this file.',
  '# Old image URLs (/wp-content/uploads/...) are handled by functions/wp-content/[[path]].js.',
  '',
  '# Old WordPress sitemaps, feeds and admin',
  '/page-sitemap.xml /sitemap-index.xml 301',
  '/case-study-sitemap.xml /sitemap-index.xml 301',
  '/sitemap_index.xml /sitemap-index.xml 301',
  '/sitemap.xml /sitemap-index.xml 301',
  '/feed/ / 301',
  '/comments/feed/ / 301',
  '/wp-admin/* / 301',
  '/wp-login.php / 301',
];
await writeFile(join(root, 'public', '_redirects'), rules.join('\n') + '\n');

// ---- image redirect function ----
const entries = Object.entries(map)
  .map(([oldUrl, file]) => [new URL(oldUrl).pathname, '/img/' + file.replace(/^src\/assets\/images\//, '')])
  .sort(([a], [b]) => a.localeCompare(b));
const body = entries.map(([from, to]) => `  ${JSON.stringify(from)}: ${JSON.stringify(to)},`).join('\n');
const fn = `// Generated by scripts/make-redirects.mjs. Old WordPress image URLs -> the same image as WebP.
const MAP = {
${body}
};

export function onRequest({ request }) {
  const url = new URL(request.url);
  // Also match WordPress resized variants: name-300x143.jpg -> name.jpg
  const original = url.pathname.replace(/-\\d+x\\d+(\\.[A-Za-z]+)$/, '$1');
  const to = MAP[url.pathname] ?? MAP[original];
  if (to) return Response.redirect(url.origin + to, 301);
  return new Response('Not found', { status: 404 });
}
`;
await mkdir(join(root, 'functions', 'wp-content'), { recursive: true });
await writeFile(join(root, 'functions', 'wp-content', '[[path]].js'), fn);
await writeFile(join(root, 'public', '_routes.json'), JSON.stringify({ version: 1, include: ['/wp-content/*'], exclude: [] }, null, 2) + '\n');
console.log(`Wrote public/_redirects (${rules.filter((l) => l && !l.startsWith('#')).length} rules), functions/wp-content/[[path]].js (${entries.length} images) and public/_routes.json`);
